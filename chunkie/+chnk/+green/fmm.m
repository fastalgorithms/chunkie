function pot = fmm(fmmfun, eps, srcinfo, targinfo, type, sigma, varargin)
%CHNK.GREEN.FMM   Fast multipole methods for evaluating the layer
%potentials of a Green's function, from an FMM for that Green's function.
%
% Syntax:
%   pot = chnk.green.fmm(fmmfun, eps, srcinfo, targinfo, type, sigma, varargin)
%   tf = chnk.green.fmm(type)
%
% Let x be targets and y be sources for these formulas, with
% n_x and n_y the corresponding unit normals at those points
% (if defined).
%
% Kernels based on the Green's function G(x,y) of KERNEL.GREEN
%
% D(x,y) = \nabla_{n_y} G(x,y)
% S(x,y) = G(x,y)
%
% and their derivatives, see KERNEL.GREEN.
%
% Note: the density should be scaled by the weights
%
% chnk.green.fmm(type) is true if the kernel type is supported.
%
% Input:
%   fmmfun - function handle, U = fmmfun(eps, srcuse, pg, targ, pgt). It
%                should return the potentials of G at the targets,
%                U.pottarg(i) = sum_j c_j G(t_i,y_j)
%                               + d_j v_j . \nabla_{y_j} G(t_i,y_j),
%                and their gradients U.gradtarg if pgt = 2, generated by
%                charges and dipoles.
%                e.g. fmmfun = @(eps,s,pg,t,pgt) hfmm2d(eps,zk,s,pg,t,pgt)
%   eps - precision requested
%   srcinfo - description of sources in ptinfo struct format, i.e.
%                ptinfo.r - positions (2,:) array
%                ptinfo.n - normal (2,:) array
%   targinfo - description of targets in ptinfo struct format,
%                ptinfo.n is needed for the normal derivatives and
%                tangential derivatives
%   type - string, determines kernel type, as in KERNEL.GREEN
%                type == 's', 'd', 'sp', 'dp', 'c', 'cp', layer potentials
%                       and their normal derivatives
%                type == 'sg', 'dg', 'cg', their gradients
%                type == 'st', tangential derivative of single layer
%                type == 's2trans', 'd2trans', 'c2trans', 'trans',
%                       'trans_rep', 'trans_rep_prime',
%                       'trans_rep_grad', 'clamped_bc', the systems
%   sigma - density, (opdims(2)*ns,ndens) for ndens densities, with the
%                components at each source interleaved
%   varargin{1} - coefs in the combined layer formulas, otherwise
%                does nothing
%
% Output:
%   pot - potential/neumann data corresponding to the kernel at the
%         target locations, (opdims(1)*nt,ndens)
%
% see also KERNEL.GREEN, CHNK.HELM2D.FMM

% row r is ops{r} of the field of charges a(r,:)*sigma, dipoles b(r,:)*sigma
if nargin == 1
    pot = ~isempty(rowinfo(fmmfun,[]));
    return
end

coef = [];
if ~isempty(varargin), coef = varargin{1}; end
[a,b,ops] = rowinfo(type,coef);
if isempty(ops)
    error('CHNK.GREEN.FMM: no fmm for type ''%s''.',type);
end
m = size(a,1);  n = size(a,2);

ns = size(srcinfo.r(:,:),2);
ndens = numel(sigma)/(n*ns);
sigma = reshape(sigma,n,ns,ndens);

if isstruct(targinfo)
    targ = targinfo.r(1:2,:);
else
    targ = targinfo(1:2,:);
end
nt = size(targ,2);

need = @(o) any(strcmp(ops,o));
if need('N'), tn = targinfo.n(1:2,:); end
if need('T'), tn = targinfo.n(1:2,:); tt = [-tn(2,:); tn(1,:)]; end
if any(b(:)), sn = srcinfo.n(1:2,:); end

pot = zeros(m*nt,ndens);

% one fmm call for each distinct source configuration
ab = [a b];
done = false(m,1);
for r0 = 1:m
    if done(r0), continue; end
    rows = find(all(ab == ab(r0,:),2) & ~done);
    done(rows) = true;
    srcuse = [];
    srcuse.sources = srcinfo.r(1:2,:);
    srcuse.nd = ndens;
    if any(ab(r0,1:n))
        srcuse.charges = reshape(ab(r0,1:n)*reshape(sigma,n,[]),ns,ndens).';
    end
    if any(ab(r0,n+1:end))
        srcuse.dipstr = reshape(ab(r0,n+1:end)*reshape(sigma,n,[]),ns,ndens).';
        if ndens == 1
            srcuse.dipvec = sn;
        else
            srcuse.dipvec = repmat(reshape(sn,1,2,ns),ndens,1,1);
        end
    end
    if ~any(ab(r0,:)), continue; end

    pgt = 1;
    if any(~strcmp(ops(rows),'P')), pgt = 2; end
    U = fmmfun(eps,srcuse,0,targ,pgt);

    for r = rows(:).'
        if strcmp(ops{r},'P')
            val = reshape(U.pottarg,ndens,nt).';
        else
            g = reshape(U.gradtarg,ndens,2,nt);
            switch ops{r}
                case 'N', w = tn;
                case 'T', w = tt;
                case 'G1', w = [1; 0];
                case 'G2', w = [0; 1];
            end
            val = (reshape(g(:,1,:),ndens,nt).*w(1,:) + ...
                reshape(g(:,2,:),ndens,nt).*w(2,:)).';
        end
        pot(r:m:end,:) = val;
    end
end

end


function [a,b,ops] = rowinfo(type,coef)
% per kernel row: charge (a) and dipole (b) weights on the density
% components, and the output, potential (P), normal (N) or tangential (T)
% derivative or gradient component (G1, G2). ops is empty without an fmm

a = [];  b = [];  ops = {};
c = coef;
if isempty(c), c = [1 1; 1 1]; end
c1 = c(1);  c2 = c(min(2,numel(c)));
switch type
    case 's',  a = 1; b = 0; ops = {'P'};
    case 'd',  a = 0; b = 1; ops = {'P'};
    case 'sp', a = 1; b = 0; ops = {'N'};
    case 'dp', a = 0; b = 1; ops = {'N'};
    case 'c',  a = c2; b = c1; ops = {'P'};
    case 'cp', a = c2; b = c1; ops = {'N'};
    case 'st', a = 1; b = 0; ops = {'T'};
    case 'sg', a = [1; 1]; b = [0; 0]; ops = {'G1'; 'G2'};
    case 'dg', a = [0; 0]; b = [1; 1]; ops = {'G1'; 'G2'};
    case 'cg', a = [c2; c2]; b = [c1; c1]; ops = {'G1'; 'G2'};
    case {'s2trans', 'clamped_bc'}
        a = [1; 1]; b = [0; 0]; ops = {'P'; 'N'};
    case 'd2trans', a = [0; 0]; b = [1; 1]; ops = {'P'; 'N'};
    case 'c2trans'
        a = [c(1,2); c(2,2)]; b = [c(1,1); c(2,1)]; ops = {'P'; 'N'};
    case 'trans'
        a = [0 c(1,2); 0 c(2,2)]; b = [c(1,1) 0; c(2,1) 0];
        ops = {'P'; 'N'};
    case 'trans_rep'
        a = [0 c2]; b = [c1 0]; ops = {'P'};
    case 'trans_rep_prime'
        a = [0 c2]; b = [c1 0]; ops = {'N'};
    case 'trans_rep_grad'
        a = [0 c2; 0 c2]; b = [c1 0; c1 0]; ops = {'G1'; 'G2'};
end

end
